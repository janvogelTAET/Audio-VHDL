package ap_design_pkg is

  -----------------------------------------------------------------------------
  -- Word width constants
  -----------------------------------------------------------------------------
  -- configured in SSM2603 register R7, field WL, supported values: 16/24 bit
  constant ADC_DW : natural := 16;  -- ADC data width
  constant DAC_DW : natural := 16;  -- DAC data width

  -----------------------------------------------------------------------------
  -- Clocking related constants for I2S interface
  -----------------------------------------------------------------------------
  -- Primary ------------------------------------------------------------------
  constant FS_KHZ   : natural :=    48;   -- sample frequency [kHz], supported values: 48/96
                                          -- configured in SSM2603 register R8, field SR 
  constant MCLK_KHZ : natural := 12288;   -- AC master clock frequency [kHz]
                                          -- generated by MMCM #2 in clk_gen.vhd
  -- Derived ------------------------------------------------------------------
  constant BCNT_MAX : natural := MCLK_KHZ/FS_KHZ; -- max. bit count value in I2S interface
  constant BCNT_BIT : natural := natural(ceil(log2(real(BCNT_MAX)))); -- # bits of BCNT

  -----------------------------------------------------------------------------
  -- ADC/DAC data records
  -----------------------------------------------------------------------------
  type t_adc_smpl is record
    l : signed(ADC_DW-1 downto 0);
    r : signed(ADC_DW-1 downto 0);
  end record;
  type t_dac_smpl is record
    l : signed(DAC_DW-1 downto 0);
    r : signed(DAC_DW-1 downto 0);
  end record;

  -----------------------------------------------------------------------------
  -- Audio Codec records
  -----------------------------------------------------------------------------
  type t_codec_mode_sel is (
    codec_mode_analog_loopback,
    codec_mode_digital_line,
    codec_mode_digital_mic
  );
  
  -----------------------------------------------------------------------------
  -- Simulation constants
  -----------------------------------------------------------------------------
  constant TS_US : time := 1000 us/FS_KHZ;  -- ADC/DAC sample period in [us]

  -----------------------------------------------------------------------------
  -- Utility Functions
  -----------------------------------------------------------------------------

  -----------------------------------------------------------------------------
  -- fix-point math (w = total number of bits, f = number of fractional bits, w >= f!)
  -----------------------------------------------------------------------------
  ---------------------------------- fix-point add with carry bit generation --
  -- # of fractional bits of sum fs := max(fa,fb)
  -- # of total bits of sum      ws := fs + max(wa-fa,wb-fb) + 1
  function f_add(a : unsigned; fa : natural;
                 b : unsigned; fb : natural) return unsigned;
  function f_add(a : signed; fa : natural;
                 b : signed; fb : natural) return signed;
  ----------------------------------------------------- fix-point saturation --
  -- # of fractional bits of result fr := fa
  -- # of total bits of result      wr := wr
  function f_sat(a : unsigned; wr : natural) return unsigned;
  function f_sat(a : signed; wr : natural) return signed;
  ------------------------------------------------------- fix-point rounding --
  -- # of total bits of result wr := wr
  function f_rnd(a : unsigned; wr : natural) return unsigned;
  function f_rnd(a : signed; wr : natural) return signed;

end package ap_design_pkg;
